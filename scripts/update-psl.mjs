// Regenerates src/lib/psl-data.js from the Public Suffix List.
// Usage: node scripts/update-psl.mjs [path-to-public_suffix_list.dat]
// Without a path, downloads https://publicsuffix.org/list/public_suffix_list.dat.
// Rules are converted to ASCII (punycode), because URL hostnames are ASCII.
import { readFile, writeFile } from "node:fs/promises";
import { domainToASCII } from "node:url";

const source = process.argv[2]
  ? await readFile(process.argv[2], "utf8")
  : await (await fetch("https://publicsuffix.org/list/public_suffix_list.dat")).text();

const version = source.match(/^\/\/ VERSION: (.+)$/m)?.[1] ?? "unknown";
const commit = source.match(/^\/\/ COMMIT: (.+)$/m)?.[1] ?? "unknown";
const rules = new Set();
for (const raw of source.split(/\r?\n/)) {
  const line = raw.trim().split(/\s/)[0];
  if (!line || line.startsWith("//")) continue;
  const exception = line.startsWith("!");
  const wildcard = line.startsWith("*.");
  const body = line.slice(exception ? 1 : wildcard ? 2 : 0);
  const ascii = domainToASCII(body);
  if (!ascii) throw new Error(`Cannot convert PSL rule: ${line}`);
  rules.add((exception ? "!" : wildcard ? "*." : "") + ascii);
}
if (rules.size < 5000) throw new Error(`Unexpectedly small list: ${rules.size} rules`);

const out = `// Generated by scripts/update-psl.mjs from the Public Suffix List
// (https://publicsuffix.org/, Mozilla Public License 2.0). Do not edit by hand.
// VERSION: ${version}
// COMMIT: ${commit}
export const PSL_VERSION = ${JSON.stringify(version)};
export const PSL_RULES = ${JSON.stringify([...rules].sort().join("\n"))};
`;
await writeFile(new URL("../src/lib/psl-data.js", import.meta.url), out);
console.log(`Wrote ${rules.size} rules, version ${version}`);
